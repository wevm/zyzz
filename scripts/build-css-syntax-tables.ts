/**
 * Generates the `zyzz_css_syntax` lexer dictionaries from css-tree's runtime data.
 * css-tree bundles mdn-data with its own patch. The Rust crate stores the same definition
 * strings and parses them lazily. `--check` fails when a checked-in table differs from the
 * regenerated one.
 * @module
 */
import * as ChildProcess from 'node:child_process'
import * as Fs from 'node:fs/promises'
import * as Module from 'node:module'
import * as Path from 'node:path'
import * as Tree from 'css-tree'

type Atrule = {
  readonly descriptors: Record<string, string | null> | null
  readonly prelude: string | null
}

type Data = {
  readonly atrules: Record<string, Atrule>
  readonly properties: Record<string, string>
  readonly types: Record<string, string>
}

type Descriptor = {
  readonly serializable: boolean
  readonly syntax: unknown
}

type LexerInternals = {
  readonly atrules: Record<
    string,
    {
      readonly descriptors: Record<string, Descriptor> | null
      readonly prelude: Descriptor | null
    }
  >
  readonly cssWideKeywords: readonly string[]
  readonly properties: Record<string, Descriptor>
  readonly types: Record<string, Descriptor>
  readonly units: Record<string, readonly string[]>
}

const root = Path.resolve(import.meta.dirname, '..')
const output = Path.join(root, 'crates/zyzz_css_syntax/src/generated')
const check = process.argv.includes('--check')
const version = (
  (await import(import.meta.resolve('css-tree/package.json'), {
    with: { type: 'json' },
  })) as { default: { version: string } }
).default.version
const header = `// Generated by scripts/build-css-syntax-tables.ts from css-tree ${version}. Do not edit.\n`
// css-tree's default export from `lib/data.js` is the mdn-data dictionary with its patch.
const data = (
  (await import(
    new URL('./data.js', import.meta.resolve('css-tree')).href
  )) as {
    default: Data
  }
).default
const lexer = Tree.lexer as unknown as LexerInternals
// css-tree resolves mdn-data from its own location, which may differ from the repository's.
const mdnVersion = (
  Module.createRequire(import.meta.resolve('css-tree'))(
    'mdn-data/package.json',
  ) as {
    version: string
  }
).version

/** Applies css-tree's `mix` handling of a syntax that may extend an absent base. */
function appendOrSet(syntax: string | null | undefined): string | null {
  if (typeof syntax === 'string' && /^\s*\|/.test(syntax))
    return syntax.replace(/^\s*\|\s*/, '')

  return syntax || null
}

/** Fails when a stored string parses to a different syntax tree than the lexer holds. */
function verify(
  label: string,
  syntax: string,
  descriptor: Descriptor | null | undefined,
): void {
  const expected = JSON.stringify(descriptor?.syntax)
  const actual = JSON.stringify(Tree.definitionSyntax.parse(syntax))

  if (expected !== actual)
    throw new Error(`${label} does not reproduce css-tree's runtime syntax.`)
}

/** Quotes a string as a Rust literal. */
function literal(value: string): string {
  return `"${value
    .replace(/[\\"]/g, (character) => `\\${character}`)
    .replace(
      /[^\x20-\x7e]/g,
      (character) => `\\u{${character.codePointAt(0)!.toString(16)}}`,
    )}"`
}

/** Sorts entries by key in byte order, which `binary_search` requires. */
function sorted<value>(
  entries: Iterable<readonly [string, value]>,
): (readonly [string, value])[] {
  return [...entries].sort(([left], [right]) =>
    left < right ? -1 : left > right ? 1 : 0,
  )
}

const types: [string, string][] = []
const generic: string[] = []

for (const [name, descriptor] of Object.entries(lexer.types)) {
  if (!descriptor.serializable) {
    generic.push(name)
    continue
  }

  const syntax = appendOrSet(data.types[name])
  if (syntax === null) throw new Error(`Type <${name}> has no source syntax.`)

  verify(`Type <${name}>`, syntax, descriptor)
  types.push([name, syntax])
}

const properties: [string, string][] = []

for (const [name, descriptor] of Object.entries(lexer.properties)) {
  const syntax = appendOrSet(data.properties[name])
  if (syntax === null) throw new Error(`Property ${name} has no source syntax.`)

  verify(`Property ${name}`, syntax, descriptor)
  properties.push([name, syntax])
}

const atrules: [string, string | null, (readonly [string, string])[]][] = []

for (const [name, atrule] of Object.entries(lexer.atrules)) {
  const source = data.atrules[name]!
  const prelude = source.prelude ? appendOrSet(source.prelude) : null
  const descriptors: [string, string][] = []

  if (prelude !== null) verify(`@${name} prelude`, prelude, atrule.prelude)
  else if (atrule.prelude) throw new Error(`@${name} lost its prelude.`)

  for (const [key, descriptor] of Object.entries(atrule.descriptors ?? {})) {
    const syntax = appendOrSet(source.descriptors?.[key])
    if (syntax === null)
      throw new Error(`@${name} ${key} has no source syntax.`)

    verify(`@${name} ${key}`, syntax, descriptor)
    descriptors.push([key, syntax])
  }

  atrules.push([name, prelude, sorted(descriptors)])
}

