if (
  JSON.stringify([...generic].sort()) !==
  JSON.stringify([...expectedGeneric].sort())
)
  throw new Error(
    `css-tree's generic types changed: ${generic.sort().join(', ')}. Update the Rust lexer.`,
  )

const pairs = (entries: readonly (readonly [string, string])[]) =>
  `&[${entries.map(([name, syntax]) => `(${literal(name)}, ${literal(syntax)})`).join(', ')}]`
const list = (values: readonly string[]) =>
  `&[${values.map(literal).join(', ')}]`
const units = Object.entries(lexer.units)

const files: Record<string, string> = {
  'data.rs': `${header}//! css-tree's lexer dictionaries: mdn-data ${mdnVersion} definitions with css-tree's patch, as
//! the runtime lexer holds them.

/// An at-rule's prelude and descriptor grammars.
pub(crate) struct Atrule {
    /// Descriptor names and grammars, sorted by name.
    pub(crate) descriptors: &'static [(&'static str, &'static str)],
    /// At-rule name without \`@\`.
    pub(crate) name: &'static str,
    /// Prelude grammar.
    pub(crate) prelude: Option<&'static str>,
}

/// Type names and grammars, sorted by name. Generic types live in code.
pub(crate) static TYPES: &[(&str, &str)] = ${pairs(sorted(types))};

/// Property names and grammars, sorted by name.
pub(crate) static PROPERTIES: &[(&str, &str)] = ${pairs(sorted(properties))};

/// At-rules, sorted by name.
pub(crate) static ATRULES: &[Atrule] = &[${sorted(
    atrules.map(
      ([name, prelude, descriptors]) =>
        [name, { descriptors, prelude }] as const,
    ),
  )
    .map(
      ([name, atrule]) =>
        `Atrule { descriptors: ${pairs(atrule.descriptors)}, name: ${literal(name)}, prelude: ${atrule.prelude === null ? 'None' : `Some(${literal(atrule.prelude)})`} }`,
    )
    .join(', ')}];

/// The CSS-wide keywords, in css-tree's order, which its match graph preserves.
pub(crate) static CSS_WIDE_KEYWORDS: &[&str] = ${list(lexer.cssWideKeywords)};

${units
  .map(
    ([group, values]) =>
      `/// \`<${group}>\` units in css-tree's order.\npub(crate) static ${group.toUpperCase()}_UNITS: &[&str] = ${list(values)};`,
  )
  .join('\n\n')}
`,
  'mod.rs': `${header}//! Data tables generated from css-tree's runtime lexer.

pub(crate) mod data;
`,
}

const stale: string[] = []

for (const [name, source] of Object.entries(files)) {
  const file = Path.join(output, name)
  // Formatting here keeps \`cargo fmt\` from rewriting generated tables.
  const contents = ChildProcess.execFileSync(
    'rustfmt',
    ['--edition', '2024', '--emit', 'stdout', '--config-path', root],
    { encoding: 'utf8', input: source, maxBuffer: 64 * 1024 * 1024 },
  )
  const previous = await Fs.readFile(file, 'utf8').catch(() => undefined)

  if (previous === contents) continue
  if (check) stale.push(Path.relative(root, file))
  else {
    await Fs.mkdir(output, { recursive: true })
    await Fs.writeFile(file, contents)
  }
}

if (stale.length)
  throw new Error(
    `Generated css-syntax tables are not up to date: ${stale.join(', ')}. Run node scripts/build-css-syntax-tables.ts.`,
  )
