/**
 * Generates the Rust compiler's React Native tables from their authoritative TypeScript modules:
 * the pinned static declaration schema and the portable scalar property domains.
 * `--check` fails when a checked-in table differs from the regenerated one.
 * @module
 */
import * as Esbuild from 'esbuild'
import * as ChildProcess from 'node:child_process'
import * as Fs from 'node:fs/promises'
import * as Path from 'node:path'
import * as Url from 'node:url'

type Tables = {
  NativeSchema: typeof import('../src/react-native/internal/NativeSchema.js')
  Scalar: typeof import('../src/react-native/internal/Scalar.js')
}

type Node = {
  readonly kind: string
  readonly properties?:
    | Readonly<Record<string, { optional: boolean; value: number }>>
    | undefined
  readonly value?: unknown
  readonly values?: readonly number[] | undefined
}

const root = Path.resolve(import.meta.dirname, '..')
const output = Path.join(root, 'crates/compiler/src/react_native/generated')
const check = process.argv.includes('--check')
const header =
  '// Generated by scripts/build-rust-native-tables.ts from TypeScript sources. Do not edit.\n'

const tables = await (async (): Promise<Tables> => {
  const temporary = await Fs.mkdtemp(
    Path.join(root, '.fixture-rust-native-tables-'),
  )

  try {
    const entry = Path.join(temporary, 'entry.ts')

    await Fs.writeFile(
      entry,
      ['NativeSchema', 'Scalar']
        .map(
          (name) =>
            `export * as ${name} from ${JSON.stringify(Path.join(root, `src/react-native/internal/${name}.ts`))}`,
        )
        .join('\n'),
    )
    await Esbuild.build({
      bundle: true,
      entryPoints: [entry],
      format: 'esm',
      outfile: Path.join(temporary, 'entry.js'),
      packages: 'external',
      platform: 'node',
    })

    return (await import(
      Url.pathToFileURL(Path.join(temporary, 'entry.js')).href
    )) as Tables
  } finally {
    await Fs.rm(temporary, { force: true, recursive: true })
  }
})()

/** Quotes a string as a Rust literal. */
function literal(value: string): string {
  return `"${value.replace(/[\\"]/g, (character) => `\\${character}`).replace(/[^\x20-\x7e]/g, (character) => `\\u{${character.codePointAt(0)!.toString(16)}}`)}"`
}

/** Formats a string list as a static Rust slice. */
function strings(values: Iterable<string>): string {
  return `&[${[...values].map(literal).join(', ')}]`
}

/** Sorts entries by key in byte order, which `binary_search` requires. */
function sorted<value>(
  entries: Iterable<readonly [string, value]>,
): (readonly [string, value])[] {
  return [...entries].sort(([left], [right]) =>
    left < right ? -1 : left > right ? 1 : 0,
  )
}

/** Converts a camelCase identifier into a Rust type or variant name. */
function pascal(value: string): string {
  return `${value[0]!.toUpperCase()}${value.slice(1)}`
}

/** Formats a number as a Rust `f64` literal. */
function float(value: number): string {
  if (!Number.isFinite(value)) throw new Error(`Unsupported number ${value}.`)
  return Number.isInteger(value) ? `${value}.0` : String(value)
}

/** Generates the static declaration schema as an indexed node table. */
function schemaTable(): string {
  const schema = tables.NativeSchema.default as {
    readonly nodes: readonly Node[]
    readonly root: number
  }

  function node(input: Node): string {
    switch (input.kind) {
      case 'array':
        return `Node::Array(${input.value as number})`
      case 'literal': {
        const value = input.value
        if (value === null) return 'Node::Literal(Literal::Null)'
        if (typeof value === 'boolean')
          return `Node::Literal(Literal::Bool(${value}))`
        if (typeof value === 'number')
          return `Node::Literal(Literal::Number(${float(value)}))`
        if (typeof value === 'string')
          return `Node::Literal(Literal::String(${literal(value)}))`
        throw new Error(`Unsupported literal ${String(value)}.`)
      }
      case 'never':
        return 'Node::Never'
      case 'number':
        return 'Node::Number'
      case 'object':
        return `Node::Object(&[${sorted(Object.entries(input.properties ?? {}))
          .map(
            ([key, property]) =>
              `(${literal(key)}, Property { optional: ${property.optional}, value: ${property.value} })`,
          )
          .join(', ')}])`
      case 'percentage':
        return 'Node::Percentage'
      case 'string':
        return 'Node::String'
      case 'tuple':
        return `Node::Tuple(&[${input.values!.join(', ')}])`
      case 'undefined':
        return 'Node::Undefined'
      case 'union':
        return `Node::Union(&[${input.values!.join(', ')}])`
      default:
        throw new Error(`Unclassified native schema kind: ${input.kind}`)
    }
  }

  return `${header}//! Static native declaration domains from \`src/react-native/internal/NativeSchema.ts\`.

/// A literal value compared with strict equality.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Literal {
    /// A boolean.
    Bool(bool),
    /// \`null\`.
    Null,
    /// A number.
    Number(f64),
    /// A string.
    String(&'static str),
}

/// An object property and whether it may be absent.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Property {
    /// Whether the property may be absent.
    pub optional: bool,
    /// Index of the property's value node.
    pub value: usize,
}

/// One schema node. Child nodes are referenced by index into [\`NODES\`].
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Node {
    /// An array whose every entry matches the indexed node.
    Array(usize),
    /// One literal value.
    Literal(Literal),
    /// No value.
    Never,
    /// A finite number.
    Number,
    /// A record with known properties, sorted by key for binary search.
    Object(&'static [(&'static str, Property)]),
    /// A finite percentage string.
    Percentage,
    /// Any string.
    String,
    /// An array matching each indexed node in order.
    Tuple(&'static [usize]),
    /// \`undefined\`.
    Undefined,
    /// Any of the indexed nodes.
    Union(&'static [usize]),
}

/// Index of the root declaration record.
pub const ROOT: usize = ${schema.root};

/// Schema nodes in source order.
pub static NODES: &[Node] = &[
${schema.nodes.map((entry) => `    ${node(entry)},`).join('\n')}
];
`
}

/** Generates the portable scalar property domains. */
function scalarTable(): string {
  const entries = sorted(
    Object.entries(tables.Scalar.properties) as [
      string,
      string | readonly string[],
    ][],
  )
  const kinds = [
    ...new Set(
      entries.flatMap(([, kind]) => (typeof kind === 'string' ? [kind] : [])),
    ),
  ].sort()

  return `${header}//! Portable native property domains from \`src/react-native/internal/Scalar.ts\`.

/// The value domain of a portable native property.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Kind {
    /// One of the listed keywords.
    Keywords(&'static [&'static str]),
${kinds.map((kind) => `    /// \`${kind}\`\n    ${pascal(kind)},`).join('\n')}
}

impl Kind {
    /// The TypeScript spelling of a named domain. Keyword lists have none.
    pub const fn as_str(self) -> Option<&'static str> {
        match self {
            Self::Keywords(_) => None,
${kinds.map((kind) => `            Self::${pascal(kind)} => Some(${literal(kind)}),`).join('\n')}
        }
    }
}

/// Domains keyed by camelCase property name, sorted for binary search.
pub static PROPERTIES: &[(&str, Kind)] = &[
${entries
  .map(
    ([name, kind]) =>
      `    (${literal(name)}, ${typeof kind === 'string' ? `Kind::${pascal(kind)}` : `Kind::Keywords(${strings(kind)})`}),`,
  )
  .join('\n')}
];

/// Looks up the domain of a camelCase property name.
pub fn property(name: &str) -> Option<Kind> {
    PROPERTIES
        .binary_search_by(|(key, _)| (*key).cmp(name))
        .ok()
        .and_then(|index| PROPERTIES.get(index))
        .map(|(_, kind)| *kind)
}
`
}

const files = {
  'mod.rs': `${header}//! React Native data tables generated from authoritative TypeScript modules.

pub mod native_schema;
pub mod scalar;
`,
  'native_schema.rs': schemaTable(),
  'scalar.rs': scalarTable(),
}

const stale: string[] = []

await Fs.mkdir(output, { recursive: true })

for (const [name, source] of Object.entries(files)) {
  const file = Path.join(output, name)
  // Formatting here keeps `cargo fmt` from rewriting generated tables.
  const contents = ChildProcess.execFileSync(
    'rustfmt',
    ['--edition', '2024', '--emit', 'stdout', '--config-path', root],
    { encoding: 'utf8', input: source, maxBuffer: 64 * 1024 * 1024 },
  )
  const previous = await Fs.readFile(file, 'utf8').catch(() => undefined)

  if (previous === contents) continue
  if (check) stale.push(Path.relative(root, file))
  else await Fs.writeFile(file, contents)
}

if (stale.length)
  throw new Error(
    `Generated Rust native tables are not up to date: ${stale.join(', ')}. Run node scripts/build-rust-native-tables.ts.`,
  )
