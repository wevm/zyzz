/**
 * Generates the Rust compiler's data tables from their authoritative TypeScript modules.
 * `--check` fails when a checked-in table differs from the regenerated one.
 * @module
 */
import * as Esbuild from 'esbuild'
import * as ChildProcess from 'node:child_process'
import * as Fs from 'node:fs/promises'
import * as Path from 'node:path'
import * as Url from 'node:url'

type Tables = {
  BindingDomains: typeof import('../src/internal/BindingDomains.js')
  Cascade: typeof import('../src/internal/Cascade.js')
  Literal: typeof import('../src/internal/Literal.js')
  Token: typeof import('../src/internal/Token.js')
}

const root = Path.resolve(import.meta.dirname, '..')
const output = Path.join(root, 'crates/zyzz_compiler/src/generated')
const check = process.argv.includes('--check')
const header =
  '// Generated by scripts/build-rust-tables.ts from TypeScript sources. Do not edit.\n'

const tables = await (async (): Promise<Tables> => {
  const temporary = await Fs.mkdtemp(Path.join(root, '.fixture-rust-tables-'))

  try {
    const entry = Path.join(temporary, 'entry.ts')

    await Fs.writeFile(
      entry,
      ['BindingDomains', 'Cascade', 'Literal', 'Token']
        .map(
          (name) =>
            `export * as ${name} from ${JSON.stringify(Path.join(root, `src/internal/${name}.ts`))}`,
        )
        .join('\n'),
    )
    await Esbuild.build({
      bundle: true,
      entryPoints: [entry],
      format: 'esm',
      outfile: Path.join(temporary, 'entry.js'),
      packages: 'external',
      platform: 'node',
    })

    return (await import(
      Url.pathToFileURL(Path.join(temporary, 'entry.js')).href
    )) as Tables
  } finally {
    await Fs.rm(temporary, { force: true, recursive: true })
  }
})()

/** Quotes a string as a Rust literal. */
function literal(value: string): string {
  return `"${value.replace(/[\\"]/g, (character) => `\\${character}`).replace(/[^\x20-\x7e]/g, (character) => `\\u{${character.codePointAt(0)!.toString(16)}}`)}"`
}

/** Formats a string list as a static Rust slice. */
function strings(values: Iterable<string>): string {
  return `&[${[...values].map(literal).join(', ')}]`
}

/** Sorts entries by key in byte order, which `binary_search` requires. */
function sorted<value>(
  entries: Iterable<readonly [string, value]>,
): (readonly [string, value])[] {
  return [...entries].sort(([left], [right]) =>
    left < right ? -1 : left > right ? 1 : 0,
  )
}

/** Converts a camelCase or kebab-case identifier into a Rust identifier. */
function snake(value: string): string {
  return value.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`)
}

/** Converts a kebab-case identifier into a Rust type or variant name. */
function pascal(value: string): string {
  return value.replace(/(?:^|-)([a-z])/g, (_, letter: string) =>
    letter.toUpperCase(),
  )
}

/** Generates the literal property rule table with one struct shape for every kind. */
function literalTable(): string {
  const rules = sorted(Object.entries(tables.Literal.rules)) as (readonly [
    string,
    Record<string, unknown>,
  ])[]
  const kinds = [...new Set(rules.map(([, rule]) => rule.kind as string))].sort()
  const fields = new Map<string, 'bool' | 'number' | 'string' | 'strings' | 'groups'>()

  for (const [, rule] of rules)
    for (const [key, value] of Object.entries(rule)) {
      if (key === 'kind') continue

      const type = (() => {
        if (typeof value === 'boolean') return 'bool' as const
        if (typeof value === 'number') return 'number' as const
        if (typeof value === 'string') return 'string' as const
        if (Array.isArray(value) && value.every((item) => typeof item === 'string'))
          return 'strings' as const
        if (Array.isArray(value) && value.every(Array.isArray))
          return 'groups' as const
        throw new Error(`Unsupported rule field ${key}.`)
      })()
      const previous = fields.get(key)
      if (previous && previous !== type)
        throw new Error(`Rule field ${key} mixes ${previous} and ${type}.`)
      fields.set(key, type)
    }

  const names = [...fields.keys()].sort((left, right) =>
    snake(left) < snake(right) ? -1 : 1,
  )
  const rust = {
    bool: 'Option<bool>',
    groups: "Option<&'static [&'static [&'static str]]>",
    number: 'Option<f64>',
    string: "Option<&'static str>",
    strings: "Option<&'static [&'static str]>",
  }

  function value(type: string, input: unknown): string {
    if (input === undefined) return 'None'
    if (type === 'bool' || type === 'string')
      return `Some(${type === 'string' ? literal(input as string) : String(input)})`
    if (type === 'number') {
      const number = input as number
      if (number === Number.POSITIVE_INFINITY) return 'Some(f64::INFINITY)'
      if (number === Number.NEGATIVE_INFINITY) return 'Some(f64::NEG_INFINITY)'
      return `Some(${Number.isInteger(number) ? `${number}.0` : String(number)})`
    }
    if (type === 'strings') return `Some(${strings(input as string[])})`
    return `Some(&[${(input as string[][]).map(strings).join(', ')}])`
  }

  return `${header}//! Literal property rules from \`src/internal/Literal.ts\`.

/// The value domain of a literal property rule.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Kind {
${kinds.map((kind) => `    /// \`${kind}\`\n    ${pascal(kind)},`).join('\n')}
}

impl Kind {
    /// The TypeScript spelling of this kind.
    pub const fn as_str(self) -> &'static str {
        match self {
${kinds.map((kind) => `            Self::${pascal(kind)} => ${literal(kind)},`).join('\n')}
        }
    }
}

/// A literal property rule. Absent fields are \`None\`, matching an omitted TypeScript key.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Rule {
${names.map((name) => `    /// \`${name}\`\n    pub ${snake(name)}: ${rust[fields.get(name)!]},`).join('\n')}
    /// \`kind\`
    pub kind: Kind,
}

impl Rule {
    /// Creates a rule of one kind with every optional field absent.
    pub const fn new(kind: Kind) -> Self {
        Self {
${names.map((name) => `            ${snake(name)}: None,`).join('\n')}
            kind,
        }
    }
}

/// Rules keyed by camelCase property name, sorted for binary search.
pub static RULES: &[(&str, Rule)] = &[
${rules
  .map(
    ([name, rule]) =>
      `    (${literal(name)}, Rule { ${names
        .filter((field) => rule[field] !== undefined)
        .map((field) => `${snake(field)}: ${value(fields.get(field)!, rule[field])}, `)
        .join('')}..Rule::new(Kind::${pascal(rule.kind as string)}) }),`,
  )
  .join('\n')}
];

/// Canonical conflict domains for legacy and vendor spellings, sorted for binary search.
pub static ALIASES: &[(&str, &str)] = &[
${sorted(Object.entries(tables.Literal.aliases as Record<string, string>))
  .map(([name, target]) => `    (${literal(name)}, ${literal(target)}),`)
  .join('\n')}
];

/// CSS-wide keywords accepted by every property.
pub static GLOBALS: &[&str] = ${strings(tables.Literal.globals)};

/// Length units in authored order.
pub static LENGTH_UNITS: &[&str] = ${strings(tables.Literal.lengthUnits)};

/// Named colors in authored order.
pub static NAMED_COLORS: &[&str] = ${strings(tables.Literal.namedColors)};

/// System colors in authored order.
pub static SYSTEM_COLORS: &[&str] = ${strings(tables.Literal.systemColors)};

/// Looks up the rule for a camelCase property name.
pub fn rule(property: &str) -> Option<&'static Rule> {
    RULES
        .binary_search_by(|(name, _)| (*name).cmp(property))
        .ok()
        .and_then(|index| RULES.get(index))
        .map(|(_, rule)| rule)
}

/// Looks up the canonical property for a legacy or vendor spelling.
pub fn alias(property: &str) -> Option<&'static str> {
    ALIASES
        .binary_search_by(|(name, _)| (*name).cmp(property))
        .ok()
        .and_then(|index| ALIASES.get(index))
        .map(|(_, target)| *target)
}
`
}

/** Generates a sorted map of string lists with a lookup function. */
function listTable(options: {
  readonly description: string
  readonly entries: Iterable<readonly [string, readonly string[]]>
  readonly lookup: string
  readonly name: string
}): string {
  return `${header}//! ${options.description}

/// Entries keyed by name, sorted for binary search. Lists keep authored order.
pub static ${options.name}: &[(&str, &[&str])] = &[
${sorted(options.entries)
  .map(([name, values]) => `    (${literal(name)}, ${strings(values)}),`)
  .join('\n')}
];

/// Looks up the authored list for a name.
pub fn ${options.lookup}(name: &str) -> Option<&'static [&'static str]> {
    ${options.name}
        .binary_search_by(|(key, _)| (*key).cmp(name))
        .ok()
        .and_then(|index| ${options.name}.get(index))
        .map(|(_, values)| *values)
}
`
}

const files = {
  'binding_domains.rs': listTable({
    description:
      'Binding kinds and the properties that accept them, from `src/internal/BindingDomains.ts`.',
    entries: Object.entries(tables.BindingDomains.properties),
    lookup: 'properties',
    name: 'PROPERTIES',
  }),
  'cascade.rs': listTable({
    description:
      'Shorthands and the longhands they reset, from `src/internal/Cascade.ts`.',
    entries: Object.entries(tables.Cascade.shorthands),
    lookup: 'shorthand',
    name: 'SHORTHANDS',
  }),
  'literal.rs': literalTable(),
  'mod.rs': `${header}//! Data tables generated from authoritative TypeScript modules.

pub mod binding_domains;
pub mod cascade;
#[expect(clippy::unreadable_literal, reason = "Numeric bounds mirror their TypeScript source spelling.")]
pub mod literal;
pub mod token;
`,
  'token.rs': listTable({
    description:
      'Ordered token category fallbacks for each property, from `src/internal/Token.ts`.',
    entries: Object.entries(tables.Token.propertyGroups),
    lookup: 'property_groups',
    name: 'PROPERTY_GROUPS',
  }),
}

const stale: string[] = []

await Fs.mkdir(output, { recursive: true })

for (const [name, source] of Object.entries(files)) {
  const file = Path.join(output, name)
  // Formatting here keeps `cargo fmt` from rewriting generated tables.
  const contents = ChildProcess.execFileSync(
    'rustfmt',
    ['--edition', '2024', '--emit', 'stdout', '--config-path', root],
    { encoding: 'utf8', input: source, maxBuffer: 64 * 1024 * 1024 },
  )
  const previous = await Fs.readFile(file, 'utf8').catch(() => undefined)

  if (previous === contents) continue
  if (check) stale.push(Path.relative(root, file))
  else await Fs.writeFile(file, contents)
}

if (stale.length)
  throw new Error(
    `Generated Rust tables are not up to date: ${stale.join(', ')}. Run pnpm update:tables.`,
  )
