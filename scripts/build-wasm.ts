/**
 * Builds the two WebAssembly compilers. The web build inlines as `src/web/internal/Wasm.generated.ts`,
 * which browser bundles import through `#wasm`. The source compiler build, with the `compiler`
 * feature, ships separately as `binding/compiler.wasm` for `zyzz/compiler/wasm`. Both outputs are
 * gitignored and rewritten only when the modules change.
 * @module
 */
import * as ChildProcess from 'node:child_process'
import * as Fs from 'node:fs'
import * as Path from 'node:path'

const root = Path.resolve(import.meta.dirname, '..')
const compiler = Path.join(root, 'binding/compiler.wasm')
const output = Path.join(root, 'src/web/internal/Wasm.generated.ts')

/** Builds the `wasm` crate and returns the module bytes. */
function build(options: build.Options = {}): Buffer {
  ChildProcess.execFileSync(
    'cargo',
    [
      'build',
      '--package',
      'wasm',
      ...(options.features ? ['--features', options.features] : []),
      '--profile',
      'wasm',
      '--target',
      'wasm32-wasip1',
      ...(options.targetDir ? ['--target-dir', options.targetDir] : []),
    ],
    { cwd: root, stdio: 'inherit' },
  )

  return Fs.readFileSync(
    Path.join(
      root,
      options.targetDir ?? 'target',
      'wasm32-wasip1/wasm/wasm.wasm',
    ),
  )
}

declare namespace build {
  type Options = {
    /** Cargo features of the `wasm` crate. */
    readonly features?: string | undefined
    /** Cargo target directory, relative to the root. Defaults to `target`. */
    readonly targetDir?: string | undefined
  }
}

/** Writes a file only when its contents change, so watchers and Cargo skip unchanged outputs. */
function write(file: string, contents: Buffer | string): void {
  if (
    Fs.existsSync(file) &&
    Fs.readFileSync(file).equals(Buffer.from(contents))
  )
    return

  Fs.mkdirSync(Path.dirname(file), { recursive: true })
  Fs.writeFileSync(file, contents)
}

const module = build()

write(
  output,
  `/** Generated by scripts/build-wasm.ts from crates/wasm. Do not edit. @module */
/** The \`crates/wasm\` web build, base64 encoded. */
export const base64: string = '${module.toString('base64')}'
`,
)

// A separate target directory keeps the feature build from replacing the web build's artifact.
write(compiler, build({ features: 'compiler', targetDir: 'target/compiler' }))
