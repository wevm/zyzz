/**
 * Builds the web WebAssembly compiler and inlines it as `src/web/internal/Wasm.generated.ts`,
 * which browser bundles import through `#wasm`. The output is gitignored and rewritten only
 * when the module changes.
 * @module
 */
import * as ChildProcess from 'node:child_process'
import * as Fs from 'node:fs'
import * as Path from 'node:path'

const root = Path.resolve(import.meta.dirname, '..')
const output = Path.join(root, 'src/web/internal/Wasm.generated.ts')

ChildProcess.execFileSync(
  'cargo',
  [
    'build',
    '--package',
    'zyzz_wasm',
    '--profile',
    'wasm',
    '--target',
    'wasm32-wasip1',
  ],
  { cwd: root, stdio: 'inherit' },
)

const module = Fs.readFileSync(
  Path.join(root, 'target/wasm32-wasip1/wasm/zyzz_wasm.wasm'),
)
const contents = `/** Generated by scripts/build-wasm.ts from crates/zyzz_wasm. Do not edit. @module */
/** The \`zyzz_wasm\` web build, base64 encoded. */
export const base64: string = '${module.toString('base64')}'
`
const previous = Fs.existsSync(output)
  ? Fs.readFileSync(output, 'utf8')
  : undefined

if (previous !== contents) Fs.writeFileSync(output, contents)
